create or replace function public.is_internal_user()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select coalesce(auth.jwt() ->> 'role', '') = 'service_role'
        or exists (
            select 1
            from public.profiles
            where id = auth.uid()
              and role_id in ('admin', 'employee')
              and approval_status = 'approved'
        );
$$;

