create table if not exists public.marketing_products (
    id uuid primary key default gen_random_uuid(),
    brand text not null,
    name text not null,
    slug text not null unique,
    sort_order integer not null default 0,
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.daily_marketing_metrics (
    id bigint generated by default as identity primary key,
    product_id uuid not null references public.marketing_products(id) on delete cascade,
    metric_date date not null,
    content_views integer not null default 0 check (content_views >= 0),
    content_posts_count integer not null default 0 check (content_posts_count >= 0),
    keyword_search_volume integer not null default 0 check (keyword_search_volume >= 0),
    site_visits integer not null default 0 check (site_visits >= 0),
    cafe24_orders integer not null default 0 check (cafe24_orders >= 0),
    cafe24_revenue bigint not null default 0 check (cafe24_revenue >= 0),
    coupang_orders integer not null default 0 check (coupang_orders >= 0),
    coupang_revenue bigint not null default 0 check (coupang_revenue >= 0),
    smartstore_orders integer not null default 0 check (smartstore_orders >= 0),
    smartstore_revenue bigint not null default 0 check (smartstore_revenue >= 0),
    ad_spend bigint not null default 0 check (ad_spend >= 0),
    source text not null default 'manual' check (source in ('manual', 'api', 'import')),
    source_details jsonb not null default '{}'::jsonb,
    created_by uuid references public.profiles(id) on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (product_id, metric_date)
);

create table if not exists public.marketing_contents (
    id uuid primary key default gen_random_uuid(),
    product_id uuid not null references public.marketing_products(id) on delete cascade,
    channel text not null check (channel in ('naver_blog', 'naver_cafe', 'other')),
    title text not null,
    url text not null unique,
    published_at timestamptz,
    is_active boolean not null default true,
    created_by uuid references public.profiles(id) on delete set null,
    created_at timestamptz not null default now()
);

create table if not exists public.daily_content_metrics (
    id bigint generated by default as identity primary key,
    content_id uuid not null references public.marketing_contents(id) on delete cascade,
    metric_date date not null,
    views integer not null default 0 check (views >= 0),
    source text not null default 'manual' check (source in ('manual', 'api', 'import')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (content_id, metric_date)
);

create index if not exists daily_marketing_metrics_date_idx
    on public.daily_marketing_metrics (metric_date desc, product_id);
create index if not exists daily_content_metrics_date_idx
    on public.daily_content_metrics (metric_date desc, content_id);

