-- Dashboard에서 분기·연간 OKR을 같은 일별 원천 데이터로 조회한다.
create or replace view public.marketing_okr_rollups
with (security_invoker = true)
as
select
    p.brand,
    m.product_id,
    date_trunc('month', m.metric_date)::date as month_start,
    date_trunc('quarter', m.metric_date)::date as quarter_start,
    date_trunc('year', m.metric_date)::date as year_start,
    sum(case
        when m.blog_views is null and m.cafe_views is null then m.content_views
        else coalesce(m.blog_views, 0) + coalesce(m.cafe_views, 0)
    end)::bigint as content_views,
    sum(m.keyword_search_volume)::bigint as keyword_search_volume,
    sum(coalesce(m.cafe24_visits, m.site_visits, 0) + coalesce(m.smartstore_visits, 0) + coalesce(m.coupang_visits, 0))::bigint as visits,
    sum(m.cafe24_orders + m.smartstore_orders + m.coupang_orders)::bigint as orders,
    sum(greatest(
        m.cafe24_revenue + m.smartstore_revenue + m.coupang_revenue,
        coalesce(m.reported_total_revenue, 0)
    ))::bigint as revenue,
    sum(m.ad_spend)::bigint as ad_spend
from public.daily_marketing_metrics m
join public.marketing_products p on p.id = m.product_id
group by p.brand, m.product_id, date_trunc('month', m.metric_date),
    date_trunc('quarter', m.metric_date), date_trunc('year', m.metric_date);

grant select on public.marketing_okr_rollups to authenticated;

-- Supabase Vault에 아래 비밀값을 등록한 뒤 매일 00:00 UTC(09:00 KST)에 호출된다.
-- marketing_collector_url: https://<project-ref>.supabase.co/functions/v1/collect-marketing
-- marketing_collector_token: Edge Function의 COLLECTOR_SECRET과 같은 값
create extension if not exists pg_cron with schema pg_catalog;
create extension if not exists pg_net with schema extensions;

create or replace function public.invoke_marketing_collector()
returns bigint
language plpgsql
security definer
set search_path = public, vault, extensions
as $$
declare
    collector_url text;
    collector_token text;
    request_id bigint;
begin
    select decrypted_secret into collector_url
    from vault.decrypted_secrets where name = 'marketing_collector_url' limit 1;
    select decrypted_secret into collector_token
    from vault.decrypted_secrets where name = 'marketing_collector_token' limit 1;

    if collector_url is null or collector_token is null then
        raise exception 'marketing collector Vault secrets are not configured';
    end if;

    select net.http_post(
        url := collector_url,
        headers := jsonb_build_object(
            'Content-Type', 'application/json',
            'x-collector-secret', collector_token
        ),
        body := jsonb_build_object(
            'metric_date', (timezone('Asia/Seoul', now())::date - 1)::text,
            'trigger', 'cron'
        )
    ) into request_id;
    return request_id;
end;
$$;

do $$
declare
    existing_job bigint;
begin
    select jobid into existing_job from cron.job where jobname = 'marketing-daily-0900-kst';
    if existing_job is not null then
        perform cron.unschedule(existing_job);
    end if;
    perform cron.schedule(
        'marketing-daily-0900-kst',
        '0 0 * * *',
        'select public.invoke_marketing_collector();'
    );
end;
$$;
