-- 출처별 부분 업데이트를 원자적으로 수행한다.
-- patch에 없는 필드는 건드리지 않아 API/시트/수동 입력이 서로 0으로 덮지 않는다.
create or replace function public.merge_daily_marketing_metric(
    p_product_id uuid,
    p_metric_date date,
    p_patch jsonb,
    p_source text default 'api',
    p_source_details jsonb default '{}'::jsonb,
    p_collection_status text default 'partial'
)
returns public.daily_marketing_metrics
language plpgsql
security definer
set search_path = public
as $$
declare
    result public.daily_marketing_metrics;
    caller_role text := coalesce(auth.jwt() ->> 'role', '');
    effective_source text;
    effective_status text;
begin
    if not public.is_internal_user() then
        raise exception 'not authorized';
    end if;

    if p_source not in ('manual', 'api', 'import') then
        raise exception 'invalid source';
    end if;

    if p_collection_status not in ('complete', 'partial', 'failed', 'manual', 'imported') then
        raise exception 'invalid collection status';
    end if;

    effective_source := case
        when caller_role = 'service_role' then p_source
        when p_source = 'import' then 'import'
        else 'manual'
    end;
    effective_status := case
        when caller_role = 'service_role' then p_collection_status
        when effective_source = 'import' then 'imported'
        else 'manual'
    end;

    insert into public.daily_marketing_metrics (
        product_id, metric_date, source, source_details, collection_status,
        collected_at, created_by
    )
    values (
        p_product_id, p_metric_date, effective_source, coalesce(p_source_details, '{}'::jsonb),
        effective_status, now(), auth.uid()
    )
    on conflict (product_id, metric_date) do nothing;

    update public.daily_marketing_metrics m
    set
        blog_views = case when p_patch ? 'blog_views' then greatest(0, (p_patch->>'blog_views')::integer) else m.blog_views end,
        cafe_views = case when p_patch ? 'cafe_views' then greatest(0, (p_patch->>'cafe_views')::integer) else m.cafe_views end,
        content_views = case when p_patch ? 'content_views' then greatest(0, (p_patch->>'content_views')::integer) else m.content_views end,
        keyword_search_volume = case when p_patch ? 'keyword_search_volume' then greatest(0, (p_patch->>'keyword_search_volume')::integer) else m.keyword_search_volume end,
        cafe24_visits = case when p_patch ? 'cafe24_visits' then greatest(0, (p_patch->>'cafe24_visits')::integer) else m.cafe24_visits end,
        site_visits = case when p_patch ? 'cafe24_visits' then greatest(0, (p_patch->>'cafe24_visits')::integer)
                           when p_patch ? 'site_visits' then greatest(0, (p_patch->>'site_visits')::integer) else m.site_visits end,
        smartstore_visits = case when p_patch ? 'smartstore_visits' then greatest(0, (p_patch->>'smartstore_visits')::integer) else m.smartstore_visits end,
        coupang_visits = case when p_patch ? 'coupang_visits' then greatest(0, (p_patch->>'coupang_visits')::integer) else m.coupang_visits end,
        tracked_visits = case when p_patch ? 'tracked_visits' then greatest(0, (p_patch->>'tracked_visits')::integer) else m.tracked_visits end,
        tracked_orders = case when p_patch ? 'tracked_orders' then greatest(0, (p_patch->>'tracked_orders')::integer) else m.tracked_orders end,
        cafe24_orders = case when p_patch ? 'cafe24_orders' then greatest(0, (p_patch->>'cafe24_orders')::integer) else m.cafe24_orders end,
        cafe24_revenue = case when p_patch ? 'cafe24_revenue' then greatest(0, (p_patch->>'cafe24_revenue')::bigint) else m.cafe24_revenue end,
        smartstore_orders = case when p_patch ? 'smartstore_orders' then greatest(0, (p_patch->>'smartstore_orders')::integer) else m.smartstore_orders end,
        smartstore_revenue = case when p_patch ? 'smartstore_revenue' then greatest(0, (p_patch->>'smartstore_revenue')::bigint) else m.smartstore_revenue end,
        coupang_orders = case when p_patch ? 'coupang_orders' then greatest(0, (p_patch->>'coupang_orders')::integer) else m.coupang_orders end,
        coupang_revenue = case when p_patch ? 'coupang_revenue' then greatest(0, (p_patch->>'coupang_revenue')::bigint) else m.coupang_revenue end,
        reported_total_revenue = case when p_patch ? 'reported_total_revenue' then greatest(0, (p_patch->>'reported_total_revenue')::bigint) else m.reported_total_revenue end,
        ad_spend = case when p_patch ? 'ad_spend' then greatest(0, (p_patch->>'ad_spend')::bigint) else m.ad_spend end,
        data_completeness = coalesce(m.data_completeness, '{}'::jsonb) || coalesce(p_patch->'data_completeness', '{}'::jsonb),
        source = effective_source,
        source_details = coalesce(m.source_details, '{}'::jsonb) || coalesce(p_source_details, '{}'::jsonb),
        collection_status = effective_status,
        collected_at = now(),
        updated_at = now()
    where m.product_id = p_product_id and m.metric_date = p_metric_date
    returning m.* into result;

    if p_patch ? 'blog_views' or p_patch ? 'cafe_views' then
        update public.daily_marketing_metrics m
        set content_views = coalesce(m.blog_views, 0) + coalesce(m.cafe_views, 0)
        where m.product_id = p_product_id and m.metric_date = p_metric_date
        returning m.* into result;
    end if;

    return result;
end;
$$;

