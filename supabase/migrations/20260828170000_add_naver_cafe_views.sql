-- 네이버 카페 본문을 열지 않고 목록 조회수 스냅샷과 일 증가분을 저장한다.

alter table public.daily_content_metrics
    add column if not exists cumulative_views bigint
        check (cumulative_views is null or cumulative_views >= 0),
    add column if not exists collection_status text not null default 'complete'
        check (collection_status in ('complete', 'baseline', 'gap', 'decrease', 'missing', 'error')),
    add column if not exists source_details jsonb not null default '{}'::jsonb;

comment on column public.daily_content_metrics.views is
    '블로그는 날짜별 방문자 수, 카페는 직전 정상 스냅샷 대비 조회 증가분';
comment on column public.daily_content_metrics.cumulative_views is
    '네이버 카페 목록에 표시된 수집 시점 누적 조회수';

create table if not exists public.marketing_cafe_article_state (
    id uuid primary key default gen_random_uuid(),
    content_id uuid not null unique
        references public.marketing_contents(id) on delete cascade,
    product_id uuid not null
        references public.marketing_products(id) on delete cascade,
    cafe_id bigint not null check (cafe_id > 0),
    article_id bigint not null check (article_id > 0),
    cafe_alias text not null check (cafe_alias ~ '^[A-Za-z0-9][A-Za-z0-9_-]{1,49}$'),
    menu_id integer check (menu_id is null or menu_id > 0),
    source_url text not null,
    published_date date not null,
    source_details jsonb not null default '{}'::jsonb,
    last_cumulative_views bigint
        check (last_cumulative_views is null or last_cumulative_views >= 0),
    last_observed_at timestamptz,
    last_metric_date date,
    last_seen_run_id uuid
        references public.marketing_ingestion_runs(id) on delete set null,
    is_active boolean not null default true,
    consecutive_errors integer not null default 0 check (consecutive_errors >= 0),
    last_error text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (product_id, cafe_id, article_id)
);

create table if not exists public.marketing_cafe_observations (
    id bigint generated by default as identity primary key,
    run_id uuid not null
        references public.marketing_ingestion_runs(id) on delete cascade,
    product_id uuid not null
        references public.marketing_products(id) on delete cascade,
    cafe_id bigint not null check (cafe_id > 0),
    article_id bigint not null check (article_id > 0),
    menu_id integer check (menu_id is null or menu_id > 0),
    cumulative_views bigint
        check (cumulative_views is null or cumulative_views >= 0),
    observed_at timestamptz not null,
    error_code text,
    error_message text,
    source_details jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    unique (run_id, product_id, cafe_id, article_id),
    check (
        (cumulative_views is not null and error_code is null)
        or (cumulative_views is null and error_code is not null)
    )
);

create index if not exists marketing_cafe_state_product_active_idx
    on public.marketing_cafe_article_state (product_id, is_active, published_date desc);
create index if not exists marketing_cafe_state_run_idx
    on public.marketing_cafe_article_state (last_seen_run_id, product_id);
create index if not exists marketing_cafe_observations_run_idx
    on public.marketing_cafe_observations (run_id, product_id);

alter table public.marketing_cafe_article_state enable row level security;
alter table public.marketing_cafe_observations enable row level security;

