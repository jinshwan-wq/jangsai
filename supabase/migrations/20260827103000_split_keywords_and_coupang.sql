create table if not exists public.daily_keyword_metrics (
    id bigint generated by default as identity primary key,
    product_id uuid not null references public.marketing_products(id) on delete cascade,
    metric_date date not null,
    keyword text not null check (length(trim(keyword)) > 0),
    search_volume integer not null check (search_volume >= 0),
    source text not null default 'manual' check (source in ('manual', 'api', 'import')),
    source_details jsonb not null default '{}'::jsonb,
    created_by uuid references public.profiles(id) on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (product_id, metric_date, keyword)
);

create index if not exists daily_keyword_metrics_lookup_idx
    on public.daily_keyword_metrics (product_id, keyword, metric_date desc);

alter table public.daily_keyword_metrics enable row level security;
create policy internal_read_daily_keyword_metrics on public.daily_keyword_metrics
for select to authenticated using (public.is_internal_user());

